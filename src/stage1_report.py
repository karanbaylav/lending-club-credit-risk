"""Stage 1 outputs: default rate by issue year (first drift plot) and the data-quality note."""
import pandas as pd

from src.db import FIGS, ROOT, TABLES
from src.style import ACCENT, GREY, WARN, plt, save


def main():
    d = pd.read_csv(TABLES / "default_rate_by_year.csv")
    fig, ax = plt.subplots(figsize=(9, 4.6))
    ax.plot(d.issue_year, d.default_rate_resolved_pct, marker="o", color=GREY, label="Lifetime default rate, resolved loans only")
    known = d[d.loans_12m_known > 0]
    ax.plot(known.issue_year, known.default_rate_12m_pct, marker="o", color=ACCENT, lw=2.2, label="Default within 12 months (all loans 18+ months old)")
    hi = d[d.pct_still_open >= 20]
    if len(hi):
        ax.axvspan(hi.issue_year.min() - 0.5, d.issue_year.max() + 0.5, color=WARN, alpha=0.07, lw=0)
        ax.text(hi.issue_year.min() - 0.4, ax.get_ylim()[1] * 0.95,
                "20%+ of loans still open:\nresolved-only rate is censored", color=WARN, va="top", fontsize=9.5)
    ax.set_ylabel("% of loans")
    ax.set_xticks(d.issue_year)
    ax.set_title("Default rate by issue year")
    ax.legend(frameon=False, loc="upper left", bbox_to_anchor=(0, -0.12), ncol=1)
    save(fig, FIGS / "s1_default_rate_by_year.png")

    funnel = pd.read_csv(TABLES / "row_funnel.csv")
    qv = pd.read_csv(TABLES / "quality_values.csv")
    keys = pd.read_csv(TABLES / "check_keys.csv")
    miss = pd.read_csv(TABLES / "missing_features.csv")
    snap = pd.read_csv(TABLES / "snapshot.csv")
    miss = miss[miss.pct_missing > 0]

    def md(df):
        cols = list(df.columns)
        out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
        out += ["| " + " | ".join(f"{v:,}" if isinstance(v, (int,)) else str(v) for v in r) + " |" for r in df.itertuples(index=False)]
        return "\n".join(out)

    note = f"""# Data-quality note (Stage 1)

Generated by `make stage1` from `reports/tables/`. Snapshot month: **{snap.snapshot_month[0]}**; loans issued {snap.first_issue[0]} to {snap.last_issue[0]}.

## Row funnel
{md(funnel)}

## Blocking checks (all must be 0)
{md(keys)}

## Impossible or suspicious values
{md(qv)}

## Missing values per feature (features with any missing)
{md(miss)}

## Default rate by issue year
{md(d)}

![Default rate by issue year](figures/s1_default_rate_by_year.png)

**Reading the drift plot.** The resolved-only default rate for recent issue years is not comparable with earlier years: many recent loans are still open, and the ones that have already finished are disproportionately early defaults and early payoffs. This is right-censoring, not better or worse lending. The 12-month rate, measured on every loan old enough to have a known 12-month outcome, is the comparable series.
"""
    (ROOT / "reports" / "DATA_QUALITY.md").write_text(note)
    print("stage 1 report written")


if __name__ == "__main__":
    main()
